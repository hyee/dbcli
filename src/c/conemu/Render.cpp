/* #81: the bit a mouse-family DECSET number owns in RcGrid::mouseModes. One function, because the mapping is
 * the storage's whole meaning and `mode_status` has to read the same table the setter wrote -- two copies of
 * eight `1 << k` expressions is how a mode ends up stored in bit 3 and answered from bit 4. */
static uint16_t mouseBit(int v)
{
  switch (v)
  {
    case 9:    return (uint16_t)(1u << 0);
    case 1000: return (uint16_t)(1u << 1);
    case 1002: return (uint16_t)(1u << 2);
    case 1003: return (uint16_t)(1u << 3);
    case 1004: return (uint16_t)(1u << 4);
    case 1005: return (uint16_t)(1u << 5);
    case 1006: return (uint16_t)(1u << 6);
    case 1015: return (uint16_t)(1u << 7);
    case 1016: return (uint16_t)(1u << 8);
    default:   return 0;                       /* no such mode: `mode_status` never asks with one */
  }
}

